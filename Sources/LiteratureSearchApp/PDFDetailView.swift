private extension NSColor {
    /// `#RRGGBB` → user-highlight color (HighlightColor.colorHex values;
    /// malformed input falls back to a neutral yellow rather than dropping
    /// the annotation).
    convenience init(litHex hex: String) {
        var s = hex.trimmingCharacters(in: .whitespaces)
        if s.hasPrefix("#") { s.removeFirst() }
        guard s.count == 6, let v = UInt32(s, radix: 16) else {
            self.init(red: 247 / 255, green: 215 / 255, blue: 116 / 255, alpha: 1)
            return
        }
        self.init(red: CGFloat((v >> 16) & 0xFF) / 255,
                  green: CGFloat((v >> 8) & 0xFF) / 255,
                  blue: CGFloat(v & 0xFF) / 255,
                  alpha: 1)
    }
}

/// Loading-state + outline bridge between the Coordinator (AppKit world) and
/// the SwiftUI placeholder / outline sidebar. `loaded == false` marks only the
/// loading window; the fingerprint-failure fail-closed path sets it back to
/// true so the blank view + stale banner stay exactly as before (placeholder
/// never replaces the `document = nil` state). 目录树由 Coordinator
/// 装载后发布，`jumpHandler` 为目录点击跳页回调（Coordinator 注入）。
final class PDFReaderState: ObservableObject {
    @Published var loaded = false
    /// 浮动操作条：当前用户选区（nil = 无选区/已隐藏）。仅在
    /// highlightStore 与 bookID 齐备时非 nil；滚动/缩放/清选区即清空。
    @Published var selectionInfo: PDFSelectionInfo?
    /// 目录树（空 = 无目录或尚未装载）。
    @Published var outline: [PDFOutlineNode] = []
    /// 当前目录来自自动目录回退（原生书签树为空且索引库 auto_toc 非空
    /// 时）；侧栏据此在底部显示「自动目录」小字，原生书签书不显示。换书由
    /// Coordinator.loadAndJump 连同 outline 一并清零。
    @Published var outlineAutoGenerated = false
    /// 目录跳页（1 起物理页）；Coordinator 装载时注入，nil 表示不可跳。
    var jumpHandler: ((Int) -> Void)?
    /// 当前物理页（1 起；0 = 尚未落地）。TTS「朗读此页」据此取页原文；
    /// Coordinator 在 finishLoad 落页与 persistPosition 翻页时同步。
    @Published var currentPage: Int = 0
    /// 统计喂点防幻影翻页——上一已喂页（0 = 未喂过/未落地）
    /// 与其属书。开书落位（0→N）与换书首落不是「翻页」：只更新本锚不喂
    /// 统计，翻页计数与足迹不虚增；真实页间跳转（前后均落地）照常喂。
    var lastStatsFedPage: Int = 0
    var lastStatsFedBookID: String?
    /// 阅读导航历史栈（去抖入栈，Sioyek 式回跳/前进；换书由详情栏重置）。
    @Published var history = ReadingHistoryStack()
    /// 锁定高亮锚点页（1 起；nil = 未锁定）；持久化由详情栏经
    /// ReadingPositionStore.save(anchorPage:) 落盘，这里只做会话内桥。
    @Published var anchorPage: Int?
    /// 缩略图栏：与 PDFView 同 document 实例联动的桥（weak——视图层级持有）。
    weak var pdfView: PDFView?

    func jump(to page: Int) { jumpHandler?(page) }

    //MARK: 页内提示（armed 提示 marks 回执 follow 横幅）

    /// 页内提示 overlay 文案（nil = 无）。自消型（marks 回执/armed 提示）
    /// 由 postHint 定时清 nil；sticky 型（follow 模式横幅）由模式退出时
    /// 显式置 nil——不静默不假称（呈现面要求）。
    @Published var readerHint: String?
    private var hintClearTask: Task<Void, Never>?

    /// 页内提示唯一写入口。autoClearSeconds = nil 表示 sticky（跟随模式
    /// 存续）；同文案到点后只在未被替换时清除（新提示不被旧计时误清）。
    func postHint(_ text: String?, autoClearSeconds: Double? = 2.5) {
        hintClearTask?.cancel()
        hintClearTask = nil
        readerHint = text
        guard text != nil, let seconds = autoClearSeconds else { return }
        let issued = text
        hintClearTask = Task { [weak self] in
            try? await Task.sleep(nanoseconds: UInt64(seconds * 1_000_000_000))
            guard !Task.isCancelled else { return }
            await MainActor.run { [weak self] in
                if self?.readerHint == issued { self?.readerHint = nil }
            }
        }
    }
}

/// 浮动操作条载体：选区 utf16 区间 + 物理页 + 选区在 PDFView 视图
/// 坐标里的 rect（SwiftUI 浮层据此定位，AppKit 原点左下 → SwiftUI 左上）。
struct PDFSelectionInfo {
    let utf16Range: Range<Int>
    let pageNumber: Int
    /// 与选区重叠的既有用户高亮 id（nil = 无重叠 → 不显示「删除」）。
    let overlappingID: Int64?
    let viewRect: CGRect
}

/// 目录节点（值类型，从 PDFOutline 递归展平；page 为 1 起物理页，nil =
/// 目的地缺失/外部文件，行禁用）。
struct PDFOutlineNode: Identifiable {
    let label: String
    let page: Int?
    let children: [PDFOutlineNode]
    /// 自动目录回退的层级缩进（0-3）；原生书签恒 0（缩进由 List 层级
    /// 自带），侧栏行按此做前导缩进。默认 0 使原生路径构造调用零改动。
    let indent: Int
    let id = UUID()

    init(label: String, page: Int?, children: [PDFOutlineNode], indent: Int = 0) {
        self.label = label
        self.page = page
        self.children = children
        self.indent = indent
    }
}

/// Paper placeholder shown while the fingerprint check + PDF parse run in
private struct PDFLoadingPlaceholder: View {
    @Environment(\.colorScheme) private var scheme
    @AppStorage("dsTheme") private var dsTheme = DS.Theme.system.rawValue

    var body: some View {
        let theme = DS.Theme.storage(dsTheme)
        return VStack(spacing: DS.Spacing.sm) {
            Image(systemName: "hourglass")
                .font(.system(size: 24))
                .foregroundStyle(DS.Color.inkSecondary(theme, scheme))
            Text(L10n.pdfLoading)
                .font(.caption)
                .foregroundStyle(DS.Color.inkSecondary(theme, scheme))
        }
        .frame(maxWidth: .infinity, maxHeight: .infinity)
        .background(DS.Color.paper(theme, scheme))
    }
}

/// PDF display + programmatic jump with ALL matched ranges highlighted.
/// Fail-closed fingerprint binding: the spec carries the expected fingerprint
/// of the file being shown and — for OCR-sourced hits — of the companion
/// original file; if EITHER drifts, the view renders nothing and raises the
/// stale flag. Highlight coordinates belong to the file named in the spec:
/// HitRouter never maps OCR-page ranges onto the original page, and the
/// "original page" view shows the original WITHOUT highlights.
///
/// SwiftUI shell around the PDFView: paper placeholder overlay during the
/// background load window only; the representable (and its Coordinator
/// state machine) is untouched by the overlay.
struct PDFDetailView: View {
    /// 选区操作条删除上抛全局 toast 撤销通道用（软删语义在 AppState；
    /// environmentObject 由 RootView 全树注入）。
    @EnvironmentObject var state: AppState
    let spec: HitRouter.OpenSpec
    /// 是否「查看原件」视图。true = 原件视图（操作条/高亮层写
    /// viewSource='original'，页码锚原件物理页）；false = 默认视图（写 'ocr'）。
    let isOriginalView: Bool
    /// Citation context for the selection context menu (the book the file
    /// belongs to; title may be nil — unknown stays unknown).
    let bookFileName: String
    let bookTitle: String?
    /// reader stores + book identity for user highlights / favorites.
    let bookID: String?
    let highlightStore: HighlightStore?
    let favoritesStore: FavoritesStore?
    @Binding var staleReference: Bool
    /// Index of the match to bring into view (within spec.highlightRanges).
    /// The page highlights ALL matches; the cursor only scrolls/selects.
    @Binding var matchCursor: Int
    /// Sioyek-style whole-document search: query + trigger token in,
    /// match count + cursor back.
    let docSearchText: String
    @Binding var docSearchToken: Int
    @Binding var docSearchCursor: Int
    @Binding var docSearchCount: Int
    @Binding var highlightsVersion: UInt64
    /// 每书阅读位置存取（页码/缩放持久）。
    let positionStore: ReadingPositionStore?
    /// 同一命中重选时恢复上次阅读页码（新命中仍为命中页跳转）。
    let restoreSavedPage: Bool
    /// 阅读器桥接状态（加载占位 + 目录树 + 跳页回调），由详情栏
    /// 持有并传入，目录侧栏与占位浮层共用同一实例。
    @ObservedObject var readerState: PDFReaderState
    /// 划词翻译：AI 已配置才允许（未配置菜单项禁用+提示）；闭包由详情栏
    /// 注入——预填 prompt 进既有 AI 确认门（预览→逐次确认，零请求不变）。
    let aiTranslateEnabled: Bool
    let onTranslate: ((String, Bool) -> Void)?
    /// Smart Jump：外链引文（externalCitation）点击回调，由详情栏注入
    /// （AppState 解析 + 跳目标书/无命中回执）；sameBookPage 就地 go(to:)。
    let onCitationTarget: ((CitationTargetKind) -> Void)?
    /// 自动目录回退：照 bookIDProvider 模式由详情栏注入（AppState 只读
    /// 入口）；Coordinator 只持闭包、不持 IndexStore（nil = 不回退）。
    let autoTOCProvider: ((String) -> [AutoTOCEntry])?
    /// 浮动操作条当前选定的颜色（黄/绿/蓝/红）。：全局记忆
    /// 「上次所用色」——@AppStorage rawValue 存取，用色动作（操作条四色）
    /// 落盘；非法存储值回退 .yellow（fail-closed，解析纯函数
    /// HighlightColor.memorized 在 Core，合成测试直测）。
    /// HighlightColor 四值既有，零 schema 改动。
    @AppStorage("lastHighlightColor") private var lastHighlightColorRaw: String = HighlightColor.yellow.rawValue
    private var barColor: HighlightColor {
        HighlightColor.memorized(lastHighlightColorRaw)
    }
    private var barColorBinding: Binding<HighlightColor> {
        Binding(get: { barColor },
                set: { lastHighlightColorRaw = $0.rawValue })
    }
    /// marks 自有表（nil = 键入时如实提示不可用，不静默）。
    let marksStore: MarksStore?
    /// 大写 marks 跨书跳转回调（bookID, 物理页）——走既有
    /// openBookPage 管线（openGuard/双指纹守卫生效）。
    let onOpenBookPage: ((String, Int) -> Void)?

    var body: some View {
        ZStack {
            PDFDetailRepresentable(spec: spec, isOriginalView: isOriginalView,
                                   bookFileName: bookFileName, bookTitle: bookTitle,
                                   bookID: bookID,
                                   printedPageResolver: { [weak state, bookID] physical in
                                       guard let bookID else { return nil }
                                       return state?.printedPage(bookID: bookID, physical: physical)
                                   },
                                   highlightStore: highlightStore,
                                   favoritesStore: favoritesStore,
                                   staleReference: $staleReference, matchCursor: $matchCursor,
                                   docSearchText: docSearchText, docSearchToken: $docSearchToken,
                                   docSearchCursor: $docSearchCursor, docSearchCount: $docSearchCount,
                                   highlightsVersion: $highlightsVersion,
                                   positionStore: positionStore, restoreSavedPage: restoreSavedPage,
                                   loadState: readerState,
                                   aiTranslateEnabled: aiTranslateEnabled,
                                   onTranslate: onTranslate,
                                   onCitationTarget: onCitationTarget,
                                   autoTOCProvider: autoTOCProvider,
                                   onAnnotationDelete: { state.requestAnnotationDelete(id: $0) },
                                   marksStore: marksStore,
                                   onOpenBookPage: onOpenBookPage)
            if !readerState.loaded {
                PDFLoadingPlaceholder()
            }
            selectionActionBarOverlay
            imageTableCaptureOverlay
            readerHintOverlay
        }
        .onChange(of: readerState.currentPage) { page in
            guard let bookID = bookID, page >= 1 else { return }
            let previous = readerState.lastStatsFedBookID == bookID
                ? readerState.lastStatsFedPage : 0
            readerState.lastStatsFedBookID = bookID
            readerState.lastStatsFedPage = page
            guard previous >= 1 else { return }
            state.recordReadingPageTurn(bookID: bookID, page: page)
        }
    }


    /// 无文字层页（扫描页）在 PDFView 结构上无可选文字 → 选区操作条永不
    /// 出现，圈选交互不可达。此入口**仅当前页无文字层时**显示：点击对
    /// 当前页整页跑图像识别（transcript 进剪贴板，提示如实标注无表格
    /// 结构）——范围是收紧不是扩张（扫描页无法框选是 PDFKit 结构限制）。
    @ViewBuilder
    private var imageTableCaptureOverlay: some View {
        if readerState.loaded, currentPageHasNoTextLayer {
            VStack {
                Spacer()
                Button(L10n.tableImageFallbackAction) {
                    makeFullPageImageTableCopy()
                }
                .buttonStyle(.bordered)
                .controlSize(.small)
                .padding(.bottom, DS.Spacing.lg)
            }
            .frame(maxWidth: .infinity)
            .allowsHitTesting(true)
        }
    }

    /// 当前页无文字层判定（page.string 为空/nil；loadState.currentPage 物理 1 起）。
    private var currentPageHasNoTextLayer: Bool {
        guard let view = readerState.pdfView,
              let document = view.document,
              readerState.currentPage >= 1,
              readerState.currentPage <= document.pageCount,
              let page = document.page(at: readerState.currentPage - 1) else { return false }
        return TableCapture.pageHasNoTextLayer(page)
    }

    private func makeFullPageImageTableCopy() {
        guard let view = readerState.pdfView,
              let document = view.document,
              readerState.currentPage >= 1,
              readerState.currentPage <= document.pageCount,
              let page = document.page(at: readerState.currentPage - 1) else { return }
        let captureRect = page.bounds(for: .cropBox)
        let appState = state
        let reader = readerState
        Task.detached(priority: .userInitiated) {
            do {
                let transcript = try await TableCapture.imageFallbackTranscript(
                    page: page, captureRect: captureRect)
                await MainActor.run {
                    appState.copyString(transcript)
                    reader.postHint(L10n.tableCopiedImageFallback)
                }
            } catch {
                await MainActor.run {
                    reader.postHint(L10n.tableCopyFailed)
                }
            }
        }
    }

    /// 选中即出的浮动操作条（高亮/四色/下划线/条件删除）。
    /// 容器禁用命中测试，只有条本身可点；条外点击自然落到 PDFView
    /// （清选区 → KVO 置 nil → 条消失）。
    @ViewBuilder
    private var selectionActionBarOverlay: some View {
        if readerState.selectionInfo != nil {
            GeometryReader { geo in
                if let info = readerState.selectionInfo {
                    SelectionActionBar(
                        color: barColorBinding,
                        canDelete: info.overlappingID != nil,
                        onHighlight: { applyBarAction(.highlight(barColor)) },
                        onUnderline: { applyBarAction(.underline(barColor)) },
                        onDelete: { applyBarAction(.delete) },
                        onSnapshot: { makeSelectionSnapshot() },
                        onTableCopy: { makeTableCopy() })
                        .position(barPosition(for: info, in: geo.size))
                }
            }
            .allowsHitTesting(false)
        }
    }

    private func barPosition(for info: PDFSelectionInfo, in size: CGSize) -> CGPoint {
        // AppKit rect（原点左下）→ SwiftUI 坐标（原点左上），条置于选区上方。
        let top = size.height - info.viewRect.maxY
        let x = min(max(info.viewRect.midX, 90), max(size.width - 90, 90))
        let y = min(max(top - 26, 22), size.height - 22)
        return CGPoint(x: x, y: y)
    }

    private enum SelectionBarAction {
        case highlight(HighlightColor)
        case underline(HighlightColor)
        case delete
    }

    /// 操作条动作唯一写盘点——仅在用户点按后落库（选中本身零写入）；
    /// 完成后 +1 版本号重贴标注、清选区收起操作条。：写入带当前
    /// 视图来源（默认 'ocr' / 原件 'original'），并把选中文本作为抗漂移锚点
    /// （与右键菜单 addHighlight 同款——不再回退索引库切片，OCR 文件页码与
    /// 索引页码可能错位，锚定材料必须来自产生选区的同一文本）。
    private func applyBarAction(_ action: SelectionBarAction) {
        defer {
            readerState.selectionInfo = nil
            readerState.pdfView?.clearSelection()
        }
        guard let info = readerState.selectionInfo,
              let store = highlightStore, let bookID else { return }
        let viewSource = isOriginalView ? HighlightStore.viewSourceOriginal : HighlightStore.viewSourceOCR
        let anchor = readerState.pdfView?.currentSelection?.string
            .map { String($0.trimmingCharacters(in: .whitespacesAndNewlines).prefix(200)) } ?? ""
        switch action {
        case .highlight(let color):
            _ = try? store.add(bookID: bookID, pageNumber: info.pageNumber,
                               utf16Start: info.utf16Range.lowerBound,
                               utf16End: info.utf16Range.upperBound,
                               color: color, anchorText: anchor, style: "highlight",
                               viewSource: viewSource)
            highlightsVersion &+= 1
        case .underline(let color):
            _ = try? store.add(bookID: bookID, pageNumber: info.pageNumber,
                               utf16Start: info.utf16Range.lowerBound,
                               utf16End: info.utf16Range.upperBound,
                               color: color, anchorText: anchor, style: "underline",
                               viewSource: viewSource)
            highlightsVersion &+= 1
        case .delete:
            guard let id = info.overlappingID else { return }
            // 软删 + toast 撤销（唯一通道；版本号在 AppState 内 bump，
            // 内存标注层重贴与撤销恢复共用同一驱动）。
            state.requestAnnotationDelete(id: id)
        }
    }

    // MARK: 快照（选区 → 独立浮动窗；复用概览缩略图渲染管线）

    /// 选区快照：页 bounds 与选区 bounds 同在页坐标系 → SnapshotGeometry.
    /// cropRatio 归一 → controller.makeSnapshot（异步渲染，零落盘零写回）。
    /// 完成即清选区收条（defer 惯例同 applyBarAction）；选区/视图不可得时
    /// 静默早退（按钮只在 selectionInfo != nil 时可见，竞态窗口极小）；
    /// 几何退化（零面积选区）同样不进渲染（SnapshotGeometry 返 nil 拒绝）。
    private func makeSelectionSnapshot() {
        defer {
            readerState.selectionInfo = nil
            readerState.pdfView?.clearSelection()
        }
        guard let view = readerState.pdfView,
              let selection = view.currentSelection,
              let page = selection.pages.first else { return }
        let controller = state.snapshotController
        let pageBounds = page.bounds(for: .cropBox)
        let selectionBounds = selection.bounds(for: page)
        guard let ratio = SnapshotGeometry.cropRatio(pageBounds: pageBounds,
                                                     selectionRect: selectionBounds) else { return }
        let pageNumber = view.document.map { $0.index(for: page) + 1 } ?? readerState.currentPage
        let title = bookTitle ?? CitationFormatter.cleanFileName(bookFileName)
        controller.makeSnapshot(page: page, cropRatio: ratio,
                                sourceTitle: title, pageNumber: pageNumber)
    }

    // MARK: 表格圈选→拷贝 TSV（文字层主路线＋VisionKit 图像回退）

    /// 圈选区（矩形拖选 bounds，页坐标系）→ 两档：
    ///   文字层：圈内词 → TableGridGeometry 聚类 → TSV 进剪贴板；
    ///   词数为 0（无文字层）：页位图 → VisionKit 图像识别 → transcript
    ///   原样进剪贴板，提示显式标注「无表格结构，未做列对齐」。
    /// 完成即清选区收条（defer 同 makeSelectionSnapshot）。识别放后台，
    /// 回执主线程（主线程纪律）。
    private func makeTableCopy() {
        defer {
            readerState.selectionInfo = nil
            readerState.pdfView?.clearSelection()
        }
        guard let view = readerState.pdfView,
              let selection = view.currentSelection,
              let page = selection.pages.first else { return }
        let captureRect = selection.bounds(for: page)
        let appState = state
        let reader = readerState
        if let result = TableCapture.textLayerTSV(page: page, captureRect: captureRect) {
            appState.copyString(result.tsv)
            reader.postHint(L10n.tableCopiedTextLayer(result.rows))
            return
        }
        // 图像回退档：异步识别（页位图渲染＋VisionKit 都不在主线程）。
        Task.detached(priority: .userInitiated) {
            do {
                let transcript = try await TableCapture.imageFallbackTranscript(
                    page: page, captureRect: captureRect)
                await MainActor.run {
                    appState.copyString(transcript)
                    reader.postHint(L10n.tableCopiedImageFallback)
                }
            } catch {
                await MainActor.run {
                    reader.postHint(L10n.tableCopyFailed)
                }
            }
        }
    }

    //页内提示胶囊（armed 提示/marks 回执/follow 横幅）。沉底
    /// 居中（阅读器桥既有 mini capsule 同区），容器禁用命中测试——不打断
    /// PDFView 交互；位置选择注：页头被 ReadingChrome 占据且键入活动期
    /// 常驻，提示放底部避免重叠（原位置与
    /// 实现记录说明）。
    @ViewBuilder
    private var readerHintOverlay: some View {
        if let hint = readerState.readerHint {
            ReaderHintCapsule(text: hint)
                .allowsHitTesting(false)
        }
    }
}

private struct ReaderHintCapsule: View {
    @Environment(\.colorScheme) private var scheme
    @AppStorage("dsTheme") private var dsTheme = DS.Theme.system.rawValue
    let text: String

    var body: some View {
        let theme = DS.Theme.storage(dsTheme)
        Text(text)
            .font(.caption)
            .foregroundStyle(DS.Color.ink(theme, scheme))
            .padding(.horizontal, DS.Spacing.sm)
            .padding(.vertical, DS.Spacing.xxs)
            .background(Capsule().fill(DS.Color.surface(theme)))
            .overlay(Capsule().stroke(DS.Color.stroke(theme, scheme), lineWidth: 1))
            .padding(.bottom, DS.Spacing.lg)
            .frame(maxWidth: .infinity, maxHeight: .infinity,
                   alignment: .bottom)
    }
}

/// 浮动操作条本体。「高亮」按当前点色落地，「下划线」同色下划线，
/// 「删除」仅在与既有高亮重叠时出现；全部文案取 L10n 键。
private struct SelectionActionBar: View {
    @Environment(\.colorScheme) private var scheme
    @AppStorage("dsTheme") private var dsTheme = DS.Theme.system.rawValue
    @Binding var color: HighlightColor
    let canDelete: Bool
    let onHighlight: () -> Void
    let onUnderline: () -> Void
    let onDelete: () -> Void
    /// 选区快照（第四钮，与高亮/下划线同排；canDelete 恒 false 时
    /// 也可见——快照不依赖与既有高亮重叠）。
    let onSnapshot: () -> Void
    /// 表格圈选→拷贝 TSV（第五钮；矩形拖选 bounds 语义与快照同源）。
    let onTableCopy: () -> Void

    private let dotLabels: [(HighlightColor, String)] = [
        (.yellow, L10n.menuHighlightYellow), (.green, L10n.menuHighlightGreen),
        (.blue, L10n.menuHighlightBlue), (.red, L10n.menuHighlightRed),
    ]

    var body: some View {
        let theme = DS.Theme.storage(dsTheme)
        let palette = DS.Color.palette(theme, scheme)
        return HStack(spacing: DS.Spacing.xs) {
            Button(L10n.highlightAction) { onHighlight() }
                .buttonStyle(.borderedProminent)
                .controlSize(.small)
            ForEach(dotLabels, id: \.0) { entry in
                Button {
                    color = entry.0
                } label: {
                    Circle()
                        .fill(swatch(entry.0))
                        .frame(width: 14, height: 14)
                        .overlay(
                            Circle()
                                .stroke(color == entry.0 ? Color(palette.ink) : .clear, lineWidth: 1.5)
                                .frame(width: 18, height: 18))
                }
                .buttonStyle(.plain)
                .accessibilityLabel(entry.1)
            }
            Button(L10n.underlineAction) { onUnderline() }
                .buttonStyle(.bordered)
                .controlSize(.small)
            // 选区快照（独立浮动窗，Skim 语义）。
            Button(L10n.snapshotAction) { onSnapshot() }
                .buttonStyle(.bordered)
                .controlSize(.small)
                .accessibilityLabel(L10n.snapshotAction)
            // 表格圈选→拷贝 TSV（文字层主路线；VisionKit 图像回退
            // 在 TableCapture 内部分档）。
            Button(L10n.tableCopyAction) { onTableCopy() }
                .buttonStyle(.bordered)
                .controlSize(.small)
                .accessibilityLabel(L10n.tableCopyAction)
            if canDelete {
                Button(L10n.actionDelete) { onDelete() }
                    .buttonStyle(.bordered)
                    .controlSize(.small)
            }
        }
        .padding(.horizontal, DS.Spacing.sm)
        .padding(.vertical, DS.Spacing.xs)
        .background(
            RoundedRectangle(cornerRadius: 10, style: .continuous)
                .fill(Color(palette.paper))
                .shadow(color: .black.opacity(0.18), radius: 4, y: 2))
        .allowsHitTesting(true)
    }

    private func swatch(_ highlightColor: HighlightColor) -> Color {
        var s = highlightColor.colorHex
        if s.hasPrefix("#") { s.removeFirst() }
        guard s.count == 6, let v = UInt32(s, radix: 16) else { return .yellow }
        return Color(.sRGB,
                     red: Double((v >> 16) & 0xFF) / 255,
                     green: Double((v >> 8) & 0xFF) / 255,
                     blue: Double(v & 0xFF) / 255)
    }
}

struct PDFDetailRepresentable: NSViewRepresentable {
    let spec: HitRouter.OpenSpec
    /// 当前是否原件视图（见 PDFDetailView 同名注释）。Coordinator
    /// 据此决定用户高亮的写入来源与渲染过滤；QuotePDFView 据此决定右键
    /// 菜单写入来源。
    let isOriginalView: Bool
    /// Citation context for the selection context menu (the book the file
    /// belongs to; title may be nil — unknown stays unknown).
    let bookFileName: String
    let bookTitle: String?
    /// reader stores + book identity for user highlights / favorites.
    let bookID: String?
    /// 引注页码换算（物理→印刷；body 注入 AppState.printedPage）
    let printedPageResolver: ((Int) -> Int?)?
    let highlightStore: HighlightStore?
    let favoritesStore: FavoritesStore?
    @Binding var staleReference: Bool
    /// Index of the match to bring into view (within spec.highlightRanges).
    /// The page highlights ALL matches; the cursor only scrolls/selects.
    @Binding var matchCursor: Int
    /// Sioyek-style whole-document search: query + trigger token in,
    /// match count + cursor back.
    let docSearchText: String
    @Binding var docSearchToken: Int
    @Binding var docSearchCursor: Int
    @Binding var docSearchCount: Int
    /// 用户高亮版本号（见 PDFDetailView 同名 binding 注释）。
    let highlightsVersion: Binding<UInt64>
    /// 每书阅读位置存取 + 同书重选页码恢复（见 PDFDetailView 注释）。
    let positionStore: ReadingPositionStore?
    let restoreSavedPage: Bool
    /// Bridge to the SwiftUI placeholder overlay + outline sidebar (loading
    /// window, TOC tree, jump callback).
    let loadState: PDFReaderState
    /// 划词翻译（见 PDFDetailView 同名注释）。
    let aiTranslateEnabled: Bool
    let onTranslate: ((String, Bool) -> Void)?
    /// Smart Jump 外链引文点击回调（见 PDFDetailView 同名注释）。
    let onCitationTarget: ((CitationTargetKind) -> Void)?
    /// 自动目录回退（见 PDFDetailView 同名注释）。
    let autoTOCProvider: ((String) -> [AutoTOCEntry])?
    /// 标注菜单删除上抛（PDFDetailView 注入 AppState 通道；
    /// nil = 菜单目标回退本地软删，无 toast）。
    let onAnnotationDelete: ((Int64) -> Void)?
    /// marks 表与跨书跳转回调（make/update 双注入，照
    /// onAnnotationDelete 先例）。
    let marksStore: MarksStore?
    let onOpenBookPage: ((String, Int) -> Void)?

    func makeNSView(context: Context) -> PDFView {
        let view = QuotePDFView()
        let coordinator = context.coordinator
        coordinator.isOriginalView = isOriginalView
        view.citationContext = { (bookFileName, bookTitle) }
        view.highlightStore = highlightStore
        view.favoritesStore = favoritesStore
        view.bookIDProvider = { [bookID] in bookID }
        view.printedPageProvider = printedPageResolver
        view.documentURLProvider = { spec.fileURL }
        view.isOriginalViewProvider = { [weak coordinator] in
            coordinator?.isOriginalView ?? false
        }
        view.aiConfiguredProvider = { [aiTranslateEnabled] in aiTranslateEnabled }
        view.onTranslateRequest = onTranslate
        view.onCitationTarget = onCitationTarget
        view.onSameBookJump = { [weak loadState] in
            guard let page = loadState?.currentPage, page >= 1 else { return }
            loadState?.history.recordJump(from: page)
        }
        view.onUserHighlightAdded = { [highlightsVersion] in
            highlightsVersion.wrappedValue &+= 1
        }
        // 删除上抛通道（软删 + toast 撤销，闭包镜像照 onTranslate 惯例）。
        view.onUserHighlightDeleted = onAnnotationDelete
        // marks 键入通道（doc_sha＝打开时已算好的 expectedFingerprint，
        // 零新增哈希；提示走阅读器桥 postHint）。
        view.marksStore = marksStore
        view.onOpenBookPage = onOpenBookPage
        view.specFingerprintProvider = { [spec] in spec.expectedFingerprint }
        view.onReaderHint = { [weak loadState] text in loadState?.postHint(text) }
        view.autoScales = true
        view.displayMode = .singlePageContinuous
        // 流畅度/质感：PDF 衬底对齐 desk 桌面色（与 SwiftUI 区底一致），
        // 页面间隙不要阴影，保持纸面连续感。渲染与瓦片由 PDFKit 内部管理
        // （无公开瓦片 API）；文档按 spec.key 复用不重载（Coordinator）。
        let scheme: ColorScheme = NSApp.effectiveAppearance
            .bestMatch(from: [.darkAqua, .aqua]) == .darkAqua ? .dark : .light
        let theme = DS.Theme.storage(UserDefaults.standard.string(forKey: "dsTheme") ?? "")
        view.backgroundColor = DS.Color.palette(theme, scheme).desk
        view.pageShadowsEnabled = false
        context.coordinator.loadState = loadState
        loadState.pdfView = view
        context.coordinator.positionStore = positionStore
        // 自动目录回退闭包镜像（照 positionStore 同款注入）。
        context.coordinator.autoTOCProvider = autoTOCProvider
        context.coordinator.installPositionTracking(on: view)
        context.coordinator.installSelectionTracking(on: view)
        context.coordinator.lastHighlightsVersion = highlightsVersion.wrappedValue
        context.coordinator.loadAndJump(view: view, spec: spec, stale: $staleReference,
                                        highlightStore: highlightStore, bookID: bookID,
                                        restoreSavedPage: restoreSavedPage)
        context.coordinator.lastCursor = matchCursor
        return view
    }

    func updateNSView(_ view: PDFView, context: Context) {
        let coordinator = context.coordinator
        coordinator.loadState = loadState
        coordinator.isOriginalView = isOriginalView
        loadState.pdfView = view
        coordinator.positionStore = positionStore
        // 自动目录回退闭包镜像（与 makeNSView 一致）。
        coordinator.autoTOCProvider = autoTOCProvider
        if let quoteView = view as? QuotePDFView {
            quoteView.highlightStore = highlightStore
            quoteView.favoritesStore = favoritesStore
            quoteView.bookIDProvider = { [bookID] in bookID }
            quoteView.isOriginalViewProvider = { [weak coordinator] in
                coordinator?.isOriginalView ?? false
            }
            quoteView.aiConfiguredProvider = { [aiTranslateEnabled] in aiTranslateEnabled }
            quoteView.onTranslateRequest = onTranslate
            quoteView.onCitationTarget = onCitationTarget
            // 删除上抛通道（与 makeNSView 一致）。
            quoteView.onUserHighlightDeleted = onAnnotationDelete
            // marks 键入通道（与 makeNSView 一致）。
            quoteView.marksStore = marksStore
            quoteView.onOpenBookPage = onOpenBookPage
            quoteView.specFingerprintProvider = { [spec] in spec.expectedFingerprint }
            quoteView.onReaderHint = { [weak loadState] text in loadState?.postHint(text) }
            quoteView.onSameBookJump = { [weak loadState] in
                guard let page = loadState?.currentPage, page >= 1 else { return }
                loadState?.history.recordJump(from: page)
            }
        }
        if coordinator.currentKey != spec.key {
            // 历史回跳：同文件重跳（同书换命中/恢复存档页）前先记当前页；
            // 跨文件（换书）不记——历史栈按书隔离，由详情栏换书时重置。
            if let oldKey = coordinator.currentKey,
               oldKey.hasPrefix(spec.fileURL.path + "#") {
                coordinator.recordHistoryJump()
            }
            coordinator.loadAndJump(view: view, spec: spec, stale: $staleReference,
                                    highlightStore: highlightStore, bookID: bookID,
                                    restoreSavedPage: restoreSavedPage)
            coordinator.lastCursor = matchCursor
            coordinator.docSearchCursor = 0
            if !docSearchText.isEmpty {
                coordinator.searchAll(view: view, text: docSearchText)
                docSearchCount = coordinator.docMatches.count
                coordinator.scrollToSearchMatch(view: view, index: 0)
            }
        } else if docSearchToken != coordinator.docSearchToken {
            coordinator.docSearchToken = docSearchToken
            coordinator.searchAll(view: view, text: docSearchText)
            docSearchCount = coordinator.docMatches.count
            docSearchCursor = 0
            coordinator.scrollToSearchMatch(view: view, index: 0)
        } else if docSearchCursor != coordinator.docSearchCursor {
            coordinator.docSearchCursor = docSearchCursor
            coordinator.scrollToSearchMatch(view: view, index: docSearchCursor)
        } else if matchCursor != coordinator.lastCursor {
            coordinator.lastCursor = matchCursor
            coordinator.scrollToMatch(view: view, index: matchCursor)
        } else if highlightsVersion.wrappedValue != coordinator.lastHighlightsVersion {
            coordinator.lastHighlightsVersion = highlightsVersion.wrappedValue
            coordinator.reapplyUserHighlights(view: view, spec: spec,
                                              highlightStore: highlightStore, bookID: bookID)
        }
    }

    func makeCoordinator() -> Coordinator { Coordinator() }

    static func dismantleNSView(_ view: PDFView, coordinator: Coordinator) {
        coordinator.removePositionTracking()
        coordinator.removeSelectionTracking()
    }

    final class Coordinator {
        var currentKey: String?
        /// 当前是否原件视图（representable 在 make/update 注入）。
        /// 用户高亮写入来源（'original'/'ocr'）与渲染过滤都据此分流。
        var isOriginalView = false
        var selections: [PDFSelection] = []
        var pages: [PDFPage] = []
        var lastCursor = 0
        /// 用户高亮版本号镜像（updateNSView 据此触发重贴）。
        var lastHighlightsVersion: UInt64 = 0
        /// Bridge to the SwiftUI placeholder overlay (nil until the
        /// representable wires it in make/updateNSView).
        var loadState: PDFReaderState?
        // In-document search state (Sioyek-style: complete match list, loop nav).
        var docSearchToken = 0
        var docSearchCursor = 0
        var docMatches: [(selection: PDFSelection, page: PDFPage)] = []
        /// 每书阅读位置存取（representable 在 make/update 注入）。
        var positionStore: ReadingPositionStore?
        /// 自动目录回退闭包（representable 在 make/update 注入；nil = 不回退）。
        var autoTOCProvider: ((String) -> [AutoTOCEntry])?
        /// 页码/缩放变化通知观察令牌（dismantle 时移除）。
        private var positionObservers: [NSObjectProtocol] = []

        // MARK: 历史回跳（去抖入栈，见 LiteratureSearchUI/ReadingHistory.swift）
        //
        // 入栈点统一走 recordHistoryJump：以阅读器桥 currentPage 为「跳前
        // 位置」。调用点：同文件重跳（updateNSView）、目录/概览跳页
        // （loadOutline 注入的 jumpHandler）、文内搜索与命中游标
        // （scrollToSearchMatch/scrollToMatch）、书内引文直跳
        // （QuotePDFView.onSameBookJump）。换书不记（历史栈按书隔离）。

        /// 跳前入栈：currentPage 未落地（< 1）时 fail-closed 忽略。
        func recordHistoryJump() {
            guard let page = loadState?.currentPage, page >= 1 else { return }
            loadState?.history.recordJump(from: page)
        }

        // MARK: 浮动操作条（currentSelection KVO）
        //
        // 用户划选 → KVO 回调组装 PDFSelectionInfo 进阅读器桥（SwiftUI 浮层
        // 据此出现）；仅 highlightStore/bookID 齐备时非 nil。滚动/缩放/换文档/
        // 清选区一律置 nil。选中本身零库写入——写入只发生在浮层按钮点按后。

        /// currentSelection KVO 令牌（dismantle 时 invalidate）。
        private var selectionObservation: NSKeyValueObservation?
        /// 滚动/缩放隐藏浮层的通知观察。
        private var selectionHideObservers: [NSObjectProtocol] = []

        func installSelectionTracking(on view: QuotePDFView) {
            guard selectionObservation == nil else { return }
            selectionObservation = view.observe(\.currentSelection, options: [.new]) { [weak self] pdfView, _ in
                self?.updateSelectionInfo(pdfView)
            }
            let center = NotificationCenter.default
            let hide: (Notification) -> Void = { [weak self] _ in
                self?.loadState?.selectionInfo = nil
            }
            selectionHideObservers = [
                center.addObserver(forName: .PDFViewPageChanged, object: view, queue: .main, using: hide),
                center.addObserver(forName: .PDFViewScaleChanged, object: view, queue: .main, using: hide),
            ]
        }

        func removeSelectionTracking() {
            selectionObservation?.invalidate()
            selectionObservation = nil
            selectionHideObservers.forEach(NotificationCenter.default.removeObserver(_:))
            selectionHideObservers = []
            loadState?.selectionInfo = nil
        }

        /// KVO 落在主线程（PDFView 的一切变更都发生在主线程）。程序化选区
        /// （命中跳转/文档检索，见 QuotePDFView.setCurrentSelection 覆写）不弹条。
        private func updateSelectionInfo(_ view: QuotePDFView) {
            guard !view.isProgrammaticSelection else { return }
            guard let selection = view.currentSelection,
                  let store = view.highlightStore,
                  let bookID = view.bookIDProvider(),
                  let page = selection.pages.first,
                  let pageText = page.string,
                  let document = view.document,
                  let range = QuotePDFView.selectionUTF16Range(selection, page: page),
                  range.lowerBound >= 0, range.upperBound <= pageText.utf16.count
            else {
                loadState?.selectionInfo = nil
                return
            }
            let pageNumber = document.index(for: page) + 1
            let bounds = selection.bounds(for: page)
            let viewRect = view.convert(bounds, from: page)
            // 与既有用户高亮重叠才允许「删除」。：只与当前视图
            // 来源的高亮判重叠——两视图页码语义不同，跨来源互不可见互不删。
            let wantedSource = isOriginalView ? HighlightStore.viewSourceOriginal : HighlightStore.viewSourceOCR
            let overlapping = (try? store.highlightsForPage(bookID: bookID, pageNumber: pageNumber,
                                                            viewSource: wantedSource))?
                .first { $0.utf16Start < range.upperBound && range.lowerBound < $0.utf16End }?
                .id
            loadState?.selectionInfo = PDFSelectionInfo(utf16Range: range, pageNumber: pageNumber,
                                                        overlappingID: overlapping, viewRect: viewRect)
        }

        /// 挂 PDFViewPageChanged / PDFViewScaleChanged 通知，把当前
        /// 页与缩放写回 per-book 存储（原书文件只读，这里只写 UserDefaults）。
        func installPositionTracking(on view: PDFView) {
            guard positionObservers.isEmpty else { return }
            let center = NotificationCenter.default
            let pageObs = center.addObserver(forName: .PDFViewPageChanged, object: view, queue: .main) { [weak view, weak self] _ in
                guard let view else { return }
                self?.persistPosition(of: view)
                // Smart Jump：翻页后预热当前页 ±1 引文扫描（后台 + 缓存）。
                self?.scanCitationsAroundCurrentPage(view)
            }
            let scaleObs = center.addObserver(forName: .PDFViewScaleChanged, object: view, queue: .main) { [weak view, weak self] _ in
                guard let view else { return }
                self?.persistPosition(of: view)
            }
            positionObservers = [pageObs, scaleObs]
        }

        func removePositionTracking() {
            positionObservers.forEach(NotificationCenter.default.removeObserver(_:))
            positionObservers = []
        }

        /// 缺页时保留存量页码，只更新缩放；缩放非法时保留存量缩放。
        private func persistPosition(of view: PDFView) {
            guard let store = positionStore,
                  let quoteView = view as? QuotePDFView,
                  let bookID = quoteView.bookIDProvider() else { return }
            let existing = store.position(for: bookID)
            let page = view.currentPage
                .flatMap { view.document?.index(for: $0) }
                .map { $0 + 1 } ?? existing?.page ?? 0
            // 无存量档且当前页解析失败：不落半条档（存储层整体拒写之外的
            // 显式早退，语义与 ReadingPositionStoreTests 锁定一致）。
            guard page >= 1 else { return }
            let scale = view.scaleFactor > 0 ? Double(view.scaleFactor) : existing?.scale ?? 0
            // 双页偏好随页/缩放一并常驻（displayMode 变更无系统通知，
            // 详情栏 toggle 另有点按即存路径，这里降级处理滚动/翻页时的落盘）。
            let twoPage = view.displayMode == .twoUpContinuous
            store.save(page: page, scale: scale, twoPage: twoPage, for: bookID)
            // 同步当前物理页给阅读器桥（TTS 朗读取页原文用）。
            if page > 0 { loadState?.currentPage = page }
        }

        // MARK: - Smart Jump 引文下划线（接线）
        //
        // 每页进视口时后台扫一次 CitationPattern（所显示文件自身的文本层，
        // page.string），主线程贴 .underline 虚线标注（kind=="citation"）。
        // 与 hit 命中高亮 / user 用户高亮三分离：任何清退循环只认自己的
        // 标记，分层互不冲突。坐标纪律：扫描与 bounds 均来自同一页对象，
        // 绝不跨文件映射；spec.highlightRanges 与本层零交互。

        /// 每页扫描缓存（0 起页索引 → 命中列表）；nil 值 = 占位（扫描中），
        /// 防滚动重复触发；换文档（loadAndJump）即清空。
        private var citationCache: [Int: [CitationMatch]] = [:]

        /// 引文下划线色：inkSecondary 低透明度；hover 加深用 inkSecondaryHighlight。
        static func citationColor(hovered: Bool) -> NSColor {
            let scheme: ColorScheme = NSApp.effectiveAppearance
                .bestMatch(from: [.darkAqua, .aqua]) == .darkAqua ? .dark : .light
            let theme = DS.Theme.storage(UserDefaults.standard.string(forKey: "dsTheme") ?? "")
            let palette = DS.Color.palette(theme, scheme)
            return (hovered ? palette.inkSecondaryHighlight : palette.inkSecondary)
                .withAlphaComponent(hovered ? 0.85 : 0.35)
        }

        /// 某页进视口（±1 预热）：后台扫描 + 主线程贴标注；每页只扫一次。
        func scanCitations(view: PDFView, pageIndex: Int) {
            guard citationCache[pageIndex] == nil,
                  let document = view.document, pageIndex < document.pageCount,
                  let page = document.page(at: pageIndex),
                  let text = page.string, !text.isEmpty else { return }
            citationCache[pageIndex] = []
            let key = currentKey
            Task.detached(priority: .utility) {
                let matches = CitationPattern.scan(text: text)
                await MainActor.run {
                    // 文档可能已在扫描期间切换：仅当 key 未变时落地。
                    guard self.currentKey == key else { return }
                    self.citationCache[pageIndex] = matches
                    self.applyCitationOverlay(view: view, pageIndex: pageIndex)
                }
            }
        }

        /// 当前页 ±1 预热（滚动无阻塞；PageChanged 与 finishLoad 共用入口）。
        func scanCitationsAroundCurrentPage(_ view: PDFView) {
            guard let document = view.document,
                  let current = view.currentPage else { return }
            let index = document.index(for: current)
            for pageIndex in [index - 1, index, index + 1]
            where pageIndex >= 0 && pageIndex < document.pageCount {
                scanCitations(view: view, pageIndex: pageIndex)
            }
        }

        /// 重贴某页引文下划线：先清该页 citation 标记者（hit/user 标注不动），
        /// 再按缓存逐命中画细虚线；命中几何同时写入 QuotePDFView 供点击测试。
        @MainActor
        private func applyCitationOverlay(view: PDFView, pageIndex: Int) {
            guard let document = view.document, pageIndex < document.pageCount,
                  let page = document.page(at: pageIndex) else { return }
            for existing in page.annotations
            where existing.type == PDFAnnotationSubtype.underline.rawValue &&
                  (existing.value(forAnnotationKey: AnnotationKindMarker.key) as? String) == AnnotationKindMarker.citation {
                page.removeAnnotation(existing)
            }
            guard let matches = citationCache[pageIndex], !matches.isEmpty,
                  let pageText = page.string else { return }
            var rects: [(CGRect, CitationMatch)] = []
            for match in matches {
                let lower = match.range.lowerBound
                let upper = match.range.upperBound
                guard lower >= 0, upper > lower, upper <= pageText.utf16.count else { continue }
                let nsRange = NSRange(location: lower, length: upper - lower)
                guard let selection = page.selection(for: nsRange),
                      let bounds = selection.bounds(for: page) as CGRect? else { continue }
                let annotation = PDFAnnotation(bounds: bounds, forType: .underline, withProperties: nil)
                annotation.color = Self.citationColor(hovered: false)
                let border = PDFBorder()
                border.lineWidth = 0.7
                border.style = .dashed
                border.dashPattern = [2, 2]
                annotation.border = border
                annotation.setValue(AnnotationKindMarker.citation, forAnnotationKey: AnnotationKindMarker.key)
                page.addAnnotation(annotation)
                rects.append((bounds, match))
            }
            (view as? QuotePDFView)?.citationRects[pageIndex] = rects
        }

        func loadAndJump(view: PDFView, spec: HitRouter.OpenSpec, stale: Binding<Bool>,
                         highlightStore: HighlightStore?, bookID: String?,
                         restoreSavedPage: Bool) {
            currentKey = spec.key
            selections = []
            pages = []
            lastCursor = 0
            // Smart Jump：换文档清空引文扫描缓存与命中几何（旧页对象随
            // 文档卸载丢弃，内存标注自然失效）。
            citationCache = [:]
            (view as? QuotePDFView)?.citationRects.removeAll()
            loadState?.selectionInfo = nil
            loadState?.loaded = false
            // 目录：换文档先清空旧树与跳页回调，finishLoad 落地后重装，
            // 杜绝上一本书的目录残留在侧栏。
            loadState?.outline = []
            loadState?.jumpHandler = nil
            // 目录来源标记一并清零，杜绝上一本书的「自动目录」标注残留。
            loadState?.outlineAutoGenerated = false
            Task.detached(priority: .userInitiated) {
                let primaryFP = try? Fingerprint.sha256Hex(ofFileAt: spec.fileURL)
                guard let primaryFP, primaryFP == spec.expectedFingerprint,
                      let document = PDFDocument(url: spec.fileURL) else {
                    await MainActor.run {
                        view.document = nil
                        stale.wrappedValue = true
                        self.loadState?.loaded = true
                    }
                    return
                }
                await MainActor.run {
                    self.finishLoad(view: view, spec: spec, document: document, stale: stale,
                                    highlightStore: highlightStore, bookID: bookID,
                                    restoreSavedPage: restoreSavedPage)
                }
            }
        }

        /// 目录：document.outlineRoot 递归展平为值类型树（侧栏懒加载由
        /// SwiftUI List(children:) 负责，此处只搬层级结构，书签体量小）。
        /// destination 缺失/页不在本文档 → page = nil（行禁用）；label 空串
        /// 降级占位文案；深度守卫防畸形树。跳页回调 1 起物理页，fail-closed
        /// 越界/缺文档不动，始终作用于当前 document。
        /// 原生树为空且 bookID/provider 齐备时，回退索引库 auto_toc
        /// （label/page 照搬，level 映射行缩进），并标记 outlineAutoGenerated
        /// 供侧栏标注「自动目录」；跳页回调与原生路径共用同一个。
        private func loadOutline(document: PDFDocument, view: PDFView, bookID: String?) {
            func walk(_ outline: PDFOutline?, depth: Int) -> [PDFOutlineNode] {
                guard let outline, depth < 64 else { return [] }
                var nodes: [PDFOutlineNode] = []
                for index in 0..<outline.numberOfChildren {
                    guard let child = outline.child(at: index) else { continue }
                    let page: Int? = child.destination.flatMap { destination in
                        destination.page.flatMap { document.index(for: $0) }
                            .flatMap { $0 == NSNotFound ? nil : $0 + 1 }
                    }
                    nodes.append(PDFOutlineNode(
                        label: (child.label?.isEmpty == false) ? child.label! : L10n.outlineEmptyLabel,
                        page: page,
                        children: walk(child, depth: depth + 1)))
                }
                return nodes
            }
            var nodes = walk(document.outlineRoot, depth: 0)
            // 自动目录回退：原生书签树为空且拿得到 bookID 时，从索引库
            // auto_toc 读自动目录（生成由索引批末 rebuildAutoTOCAll 负责，
            // 这里只读不回写；原书文件零触碰）。entries 平铺、level 0-3 直接
            // 映射为行缩进；page 本就 1 起物理页，跳页回调与原生路径共用。
            if nodes.isEmpty, let bookID, let provider = autoTOCProvider {
                let entries = provider(bookID)
                if !entries.isEmpty {
                    nodes = entries.map {
                        PDFOutlineNode(label: $0.label, page: $0.page, children: [], indent: $0.level)
                    }
                    loadState?.outlineAutoGenerated = true
                }
            }
            loadState?.outline = nodes
            loadState?.jumpHandler = { [weak self, weak view] page in
                guard let view, let document = view.document,
                      page >= 1, page <= document.pageCount,
                      let target = document.page(at: page - 1) else { return }
                // 历史回跳：目录/概览跳页入栈（去抖由栈内负责）。
                self?.recordHistoryJump()
                view.go(to: target)
            }
        }

        /// MainActor 落地（与原同步体逐字一致）：配对原件指纹复查 → document
        /// 赋值 → 跳物理页 → 全量高亮。指纹失败路径在 loadAndJump 内已处理。
        @MainActor
        private func finishLoad(view: PDFView, spec: HitRouter.OpenSpec,
                                document: PDFDocument, stale: Binding<Bool>,
                                highlightStore: HighlightStore?, bookID: String?,
                                restoreSavedPage: Bool) {
            if let companionURL = spec.companionFileURL, let companionFP = spec.companionFingerprint {
                let companionNow = try? Fingerprint.sha256Hex(ofFileAt: companionURL)
                guard companionNow == companionFP else {
                    view.document = nil
                    stale.wrappedValue = true
                    loadState?.loaded = true
                    return
                }
            }
            stale.wrappedValue = false
            view.document = document
            loadState?.loaded = true
            // 目录：装载书签树 + 注入跳页回调（1 起物理页，fail-closed）；
            // 原生树为空时按 bookID 回退索引库自动目录。
            loadOutline(document: document, view: view, bookID: bookID)
            if let bookID, let store = positionStore, let saved = store.position(for: bookID) {
                view.displayMode = saved.twoPage ? .twoUpContinuous : .singlePageContinuous
                if saved.scale > 0 {
                    view.autoScales = false
                    view.scaleFactor = CGFloat(saved.scale)
                    // PDFKit 可能在 displayMode 切换后的首次布局重置缩放
                    // 延迟一拍校验一次，漂移才回写，不成环。
                    DispatchQueue.main.async { [weak view] in
                        guard let view, !view.autoScales,
                              abs(view.scaleFactor - CGFloat(saved.scale)) > 0.01 else { return }
                        view.scaleFactor = CGFloat(saved.scale)
                    }
                }
                if restoreSavedPage, saved.page >= 1, saved.page <= document.pageCount {
                    if let savedPage = document.page(at: saved.page - 1) {
                        view.go(to: savedPage)
                    }
                    loadState?.currentPage = saved.page
                    applyHighlights(view: view, spec: spec, document: document,
                                    highlightStore: highlightStore, bookID: bookID)
                    scanCitationsAroundCurrentPage(view)
                    return
                }
            }
            guard spec.physicalPage >= 1, let page = document.page(at: spec.physicalPage - 1) else { return }
            view.go(to: page)
            loadState?.currentPage = spec.physicalPage
            applyHighlights(view: view, spec: spec, document: document,
                            highlightStore: highlightStore, bookID: bookID)
            scanCitationsAroundCurrentPage(view)
        }

        /// 命中框色：青系独立色——用户四色色板（黄/绿/蓝/红
        /// HighlightColor）之外的颜色通道（Sioyek 每类覆盖物独立色通道先例）。
        static let hitBorderColor = NSColor(calibratedRed: 0, green: 0.72, blue: 0.82, alpha: 1)

        /// 命中框/用户高亮的页文本统一取数口（侧车
        /// 缝合点）。命中条件＝显式开启（UserDefaults 调试键，默认关＝逐字
        /// 节现行为）＋非 OCR 视图（showsOCRText 页文本属 OCR 文件，而缓存键
        /// 是原件指纹，不接）＋侧车键内三元校验命中＋与 PDFKit 现抽文本同长
        /// （必要条件防错位闸）。任何一门不过 → 回落 PDFKit 现抽 page.string。
        /// page.selection(for:) 恒对真实 PDFKit 页面求值——坐标永不出自缓存
        /// 文本。A 线「已对齐」写时标志落地后，把「同长闸＋显式开关」升级为
        /// 标志判定即可（缝已收在本函数，≤10 行）。
        private func pageTextForHighlights(page: PDFPage, spec: HitRouter.OpenSpec) -> String? {
            let live = page.string
            guard UserDefaults.standard.bool(forKey: "search.highlightSidecarEnabled"),
                  !spec.showsOCRText else { return live }
            return PDFHighlightTextSource.shared.alignedPageText(
                fingerprint: spec.expectedFingerprint,
                pageNumber: spec.physicalPage, live: live) ?? live
        }

        /// 命中框 + 用户高亮重贴（finishLoad 原内联体原样抽出，两处调用
        /// 点语义逐字不变；仅为页码恢复分支复用而抽取）。
        @MainActor
        private func applyHighlights(view: PDFView, spec: HitRouter.OpenSpec,
                                     document: PDFDocument,
                                     highlightStore: HighlightStore?, bookID: String?) {
            guard spec.physicalPage >= 1, let page = document.page(at: spec.physicalPage - 1) else { return }
            // 本页校验文本经缝合口取（默认＝PDFKit 现抽，见函数注）。
            let highlightPageText = pageTextForHighlights(page: page, spec: spec)

            // 打新命中框前先移除该页既有「检索命中」框（仅带 hit 标记者，
            // 用户高亮带 user 标记不受影响；其他标注类型一律保留）——
            // 治「越读越花」：同页反复命中时旧框不再叠加。
            // （历史态兼容：旧 .highlight+hit 形态同轮清退——内存态
            // 不跨会话，仅防同会话内混形。）
            for existing in page.annotations {
                let marked = (existing.value(forAnnotationKey: AnnotationKindMarker.key) as? String) == AnnotationKindMarker.hit
                guard marked else { continue }
                let typeName = (existing.type ?? "").lowercased()
                if typeName.contains("highlight") || typeName.contains("square") {
                    page.removeAnnotation(existing)
                }
            }
            var firstSelection: (selection: PDFSelection, bounds: CGRect)?
            for range in spec.highlightRanges {
                let lower = range.lowerBound
                let upper = range.upperBound
                guard lower >= 0, upper > lower, upper <= (highlightPageText?.utf16.count ?? 0) else { continue }
                let nsRange = NSRange(location: lower, length: upper - lower)
                guard let selection = page.selection(for: nsRange) else { continue }
                let boundsForNav = selection.bounds(for: page)
                guard !boundsForNav.isEmpty else { continue }
                let frame = boundsForNav.insetBy(dx: -1.5, dy: -1.5)
                let annotation = PDFAnnotation(bounds: frame, forType: .square, withProperties: nil)
                annotation.color = Self.hitBorderColor
                annotation.interiorColor = NSColor.clear
                let border = PDFBorder()
                border.lineWidth = 1.2
                border.style = .solid
                annotation.border = border
                annotation.setValue(AnnotationKindMarker.hit, forAnnotationKey: AnnotationKindMarker.key)
                page.addAnnotation(annotation)
                selections.append(selection)
                pages.append(page)
                if firstSelection == nil {
                    firstSelection = (selection, boundsForNav)
                }
            }
            if let bookID, let highlightStore, let pageText = highlightPageText {
                let wantedSource = isOriginalView ? HighlightStore.viewSourceOriginal
                                                  : HighlightStore.viewSourceOCR
                let stored = (try? highlightStore.verifiedHighlightsForPage(
                    bookID: bookID, pageNumber: spec.physicalPage, pageText: pageText,
                    viewSource: wantedSource)) ?? []
                for highlight in stored {
                    let lower = highlight.utf16Start
                    let upper = highlight.utf16End
                    guard lower >= 0, upper > lower, upper <= pageText.utf16.count else { continue }
                    let nsRange = NSRange(location: lower, length: upper - lower)
                    guard let selection = page.selection(for: nsRange),
                          let bounds = selection.bounds(for: page) as CGRect? else { continue }
                    let annotation = QuotePDFView.makeUserAnnotation(
                        id: highlight.id, color: highlight.color, style: highlight.style, bounds: bounds)
                    page.addAnnotation(annotation)
                }
            }
            if let located = firstSelection {
                view.setCurrentSelection(located.selection, animate: true)
                view.scrollSelectionToVisible(nil)
            }
        }

        /// Brings match `index` into view (clamped); re-selects without
        /// reloading the document or touching any guard state.
        func scrollToMatch(view: PDFView, index: Int) {
            guard selections.indices.contains(index) else { return }
            // 历史回跳：命中游标跳页入栈。
            recordHistoryJump()
            let selection = selections[index]
            view.setCurrentSelection(selection, animate: true)
            view.scrollSelectionToVisible(nil)
            view.go(to: pages[index])
        }

        /// 用户高亮重贴：清退全文档 `user` 标记住内存标注后按库重画。
        /// 按当前视图来源渲染——默认视图只渲 'ocr'，原件视图只渲
        /// 'original'（两视图页码语义不同，跨来源互不串显）。'ocr' 走既有
        /// 库文本校验路径（verifiedHighlightsForBook）；'original' 的锚定
        /// 材料必须是当前 document（原件）的 PDFKit 页文本——写入即锚原件
        /// 文本，而索引库 text_original 对扫描书是 OCR 文本，不能作校验源。
        /// 渲染前双重校验：仅绘制 anchorVerified == 1 的有效高亮，失效项排除；
        /// 越界/缺页 fail-closed 跳过；检索命中（`hit`）标注与其他标注不动。
        func reapplyUserHighlights(view: PDFView, spec: HitRouter.OpenSpec,
                                   highlightStore: HighlightStore?, bookID: String?) {
            guard let bookID, let highlightStore,
                  let document = view.document else { return }
            for index in 0..<document.pageCount {
                guard let page = document.page(at: index) else { continue }
                // 按 kind 标记者清退（不限 subtype——下划线与荧光
                // 高亮两种形态都要被重贴带走）。
                for existing in page.annotations
                where (existing.value(forAnnotationKey: AnnotationKindMarker.key) as? String) == AnnotationKindMarker.user {
                    page.removeAnnotation(existing)
                }
            }
            func draw(_ highlight: UserHighlight) {
                guard let page = document.page(at: highlight.pageNumber - 1),
                      let pageText = page.string else { return }
                let lower = highlight.utf16Start
                let upper = highlight.utf16End
                guard lower >= 0, upper > lower, upper <= pageText.utf16.count else { return }
                let nsRange = NSRange(location: lower, length: upper - lower)
                guard let selection = page.selection(for: nsRange),
                      let bounds = selection.bounds(for: page) as CGRect? else { return }
                let annotation = QuotePDFView.makeUserAnnotation(
                    id: highlight.id, color: highlight.color, style: highlight.style, bounds: bounds)
                page.addAnnotation(annotation)
            }
            if isOriginalView {
                // 原件视图：'original' 来源，逐条对当前 document 页文本校验（可重锚）。
                let stored = (try? highlightStore.highlightsForBook(
                    bookID, viewSource: HighlightStore.viewSourceOriginal)) ?? []
                for highlight in stored {
                    let pageText = document.page(at: highlight.pageNumber - 1)?.string
                    guard let verified = try? highlightStore.verifyAndAnchor(highlight: highlight,
                                                                             pageText: pageText),
                          verified.anchorVerified == 1 else { continue }
                    draw(verified)
                }
            } else {
                // 默认视图：'ocr' 来源，既有路径（索引库页文本校验）。
                let stored = (try? highlightStore.verifiedHighlightsForBook(
                    bookID, viewSource: HighlightStore.viewSourceOCR)) ?? []
                for highlight in stored where highlight.anchorVerified == 1 {
                    draw(highlight)
                }
            }
        }

        /// Whole-document search (never truncated): every occurrence of `text`.
        func searchAll(view: PDFView, text: String) {            docMatches = []
            docSearchCursor = 0
            let trimmed = text.trimmingCharacters(in: .whitespaces)
            guard !trimmed.isEmpty, let document = view.document else { return }
            for selection in document.findString(trimmed, withOptions: [.caseInsensitive]) {
                guard let page = selection.pages.first else { continue }
                docMatches.append((selection, page))
            }
        }

        func scrollToSearchMatch(view: PDFView, index: Int) {
            guard docMatches.indices.contains(index) else { return }
            // 历史回跳：文内搜索跳页入栈。
            recordHistoryJump()
            let match = docMatches[index]
            view.go(to: match.page)
            view.setCurrentSelection(match.selection, animate: true)
            view.scrollSelectionToVisible(nil)
        }
    }
}

extension HitRouter.OpenSpec {
    /// Identity of what is loaded — changing any part reloads + re-verifies.
    var key: String {
        "\(fileURL.path)#\(physicalPage)#\(expectedFingerprint)#\(companionFingerprint ?? "-")#" +
        highlightRanges.map { "\($0.lowerBound)-\($0.upperBound)" }.joined(separator: ",")
    }
}

