    override func rightMouseDown(with event: NSEvent) {
        guard let menu = quoteMenuIfSelected() else {
            super.rightMouseDown(with: event)
            return
        }
        menu.popUp(positioning: nil, at: convert(event.locationInWindow, from: nil), in: self)
    }

    override func menu(for event: NSEvent) -> NSMenu? {
        quoteMenuIfSelected() ?? super.menu(for: event)
    }

    // MARK: - Smart Jump 引文交互（hover 加深 + pointingHand；点击跳转）

    override func updateTrackingAreas() {
        super.updateTrackingAreas()
        if let old = citationTrackingArea { removeTrackingArea(old) }
        let options: NSTrackingArea.Options = [.mouseMoved, .mouseEnteredAndExited, .activeInKeyWindow]
        let area = NSTrackingArea(rect: bounds, options: options, owner: self)
        addTrackingArea(area)
        citationTrackingArea = area
    }

    override func mouseMoved(with event: NSEvent) {
        if let hit = citationMatch(at: event) {
            if hoveredCitation !== hit.annotation {
                restoreHoveredCitation()
                hoveredCitation = hit.annotation
                hit.annotation.color = PDFDetailRepresentable.Coordinator.citationColor(hovered: true)
            }
            NSCursor.pointingHand.set()
        } else {
            restoreHoveredCitation()
            NSCursor.arrow.set()
        }
        super.mouseMoved(with: event)
    }

    override func mouseExited(with event: NSEvent) {
        restoreHoveredCitation()
        NSCursor.arrow.set()
        super.mouseExited(with: event)
    }

    override func mouseDown(with event: NSEvent) {
        if armedState.armedMode == .follow {
            let point = convert(event.locationInWindow, from: nil)
            if let idx = followBadgeViews.firstIndex(where: { $0.frame.contains(point) }),
               followCandidates.indices.contains(idx) {
                selectFollowCandidate(at: idx)
            } else {
                exitFollowMode()
            }
            return
        }
        // armed 设标/跳回中点击 = 取消（防 stuck armed；vim 同语义）。
        if armedState.isArmed {
            armedState.cancel()
            onReaderHint?(nil)
        }
        if let hit = citationMatch(at: event) {
            // 书内直跳：当前文档内 go(to:)；越界/缺页 fail-closed 不动。
            // 落页后 PDFViewPageChanged 通知会照常持久阅读位置。
            // 历史回跳：引文直跳入栈。
            dispatchCitationTarget(hit.match)
            return
        }
        // 点击既有用户高亮 → 操作菜单（换色/切样式/删除）。
        if presentUserHighlightMenuIfNeeded(at: event) { return }
        super.mouseDown(with: event)
    }

    /// 引文命中统一跳转分派——mouseDown 与 follow 模式（字母选定/
    /// 轮换回车）共用同一分支（sameBookPage 直跳＋历史栈／externalCitation
    /// 上抛）。。
    private func dispatchCitationTarget(_ match: CitationMatch) {
        switch match.target {
        case .sameBookPage(let page):
            guard let document, page >= 1, page <= document.pageCount,
                  let targetPage = document.page(at: page - 1) else { return }
            onSameBookJump?()
            go(to: targetPage)
        case .externalCitation:
            onCitationTarget?(match.target)
        }
    }

    //MARK: 键盘入口（全仓唯一新增 keyDown 覆盖）

    override func keyDown(with event: NSEvent) {
        if consumeReaderKey(event) { return }
        super.keyDown(with: event)
    }

    /// 键盘事件判定。返回 true = 已消费；false = 放行 super（PDFView 无文本
    /// 输入场景，space/方向键等系统键在非 armed 时零受影响——判定即：非
    /// 模式键且非 armed 一律 false）。
    private func consumeReaderKey(_ event: NSEvent) -> Bool {
        if event.keyCode == 53 { // ESC
            guard armedState.isArmed else { return false }
            exitFollowMode()
            return true
        }
        switch armedState.armedMode {
        case .markSet, .markJump:
            guard let char = event.charactersIgnoringModifiers?.first,
                  char.isASCII, char.isLetter else {
                // 其他键取消 armed 并放行原事件。
                armedState.cancel()
                onReaderHint?(nil)
                return false
            }
            let mode = armedState.consume()
            onReaderHint?(nil)
            if mode == .markSet {
                setMark(symbol: char)
            } else {
                jumpToMark(symbol: char)
            }
            return true
        case .follow:
            return consumeFollowKey(event)
        case .none:
            switch event.charactersIgnoringModifiers {
            case "m":
                armedState.arm(.markSet)
                onReaderHint?(L10n.marksArmSet)
                return true
            case "'":
                armedState.arm(.markJump)
                onReaderHint?(L10n.marksArmJump)
                return true
            case "f":
                return armFollowMode()
            default:
                return false
            }
        }
    }

    // MARK: marks（设标/跳回）

    /// 设标：小写＝文档行（doc_sha=本文件指纹），大写＝全局行（doc_sha=''
    /// 哨兵＋target_doc_sha=本文件指纹）。offset_y＝页内可见比例纯函数
    private func setMark(symbol: Character) {
        guard let store = marksStore,
              let docSHA = specFingerprintProvider(), !docSHA.isEmpty,
              let pageNumber = currentPageNumber(),
              let document, let pageObject = document.page(at: pageNumber - 1) else {
            onReaderHint?(L10n.marksStoreUnavailable)
            return
        }
        let pageBoundsInView = convert(pageObject.bounds(for: .cropBox), from: pageObject)
        let offset = MarkOffset.visibleRatio(pageBounds: pageBoundsInView,
                                             visibleRect: visibleRect)
        let isGlobal = symbol.isUppercase
        let now = Date().timeIntervalSince1970
        let mark = BookMark(
            docSHA: isGlobal ? "" : docSHA,
            symbol: String(symbol),
            targetDocSHA: isGlobal ? docSHA : nil,
            page: pageNumber,
            offsetY: offset,
            zoom: Double(scaleFactor),
            createdAt: now, modifiedAt: now)
        do {
            try store.set(mark, at: now)
            onReaderHint?(L10n.markSetDone(String(symbol)))
        } catch {
            onReaderHint?(L10n.marksStoreUnavailable)
        }
    }

    /// 跳回：小写查本文档行；大写查全局行——target 即本文档则页内跳，否则
    /// 指纹反查 bookID 经 onOpenBookPage 跨书（既有 openBookPage 管线）。
    /// 未命中如实提示「无此标记」，不静默不猜。
    private func jumpToMark(symbol: Character) {
        guard let store = marksStore,
              let docSHA = specFingerprintProvider(), !docSHA.isEmpty else {
            onReaderHint?(L10n.marksStoreUnavailable)
            return
        }
        guard let mark = try? store.mark(docSHA: docSHA, symbol: String(symbol)) else {
            onReaderHint?(L10n.markNotFound)
            return
        }
        if mark.targetDocSHA == nil || mark.targetDocSHA == docSHA {
            jumpWithinDocument(to: mark.page)
        } else {
            let bookID = try? store.bookID(fingerprint: mark.targetDocSHA ?? "")
            guard let bookID else {
                onReaderHint?(L10n.markTargetMissing)
                return
            }
            onOpenBookPage?(bookID, mark.page)
        }
    }

    private func jumpWithinDocument(to page: Int) {
        guard let document, page >= 1, page <= document.pageCount,
              let target = document.page(at: page - 1) else {
            onReaderHint?(L10n.markNotFound)
            return
        }
        onSameBookJump?()
        go(to: target)
    }

    /// 当前物理页（1 起；nil = 未落地/越界）。
    private func currentPageNumber() -> Int? {
        guard let document, let current = currentPage else { return nil }
        let index = document.index(for: current) + 1
        return index >= 1 && index <= document.pageCount ? index : nil
    }

    // MARK: follow 模式（f 键候选角标＋轮换降级处理）

    /// 进入 follow：取当前页 citationRects 既有缓存铺角标；空页/无候选短
    /// 提示不进模式（仍消费 f——不向 PDFView 透传无效键）。
    private func armFollowMode() -> Bool {
        guard let document, let current = currentPage else { return false }
        let pageIndex = document.index(for: current)
        let rects = citationRects[pageIndex] ?? []
        guard let page = document.page(at: pageIndex), !rects.isEmpty else {
            onReaderHint?(L10n.followNoCandidates)
            return true
        }
        followCandidates = rects.map { (bounds: $0.0, page: page, match: $0.1) }
        armedState.arm(.follow)
        installFollowBadges()
        updateRotationVisual()
        onReaderHint?(followStatus())
        return true
    }

    private func installFollowBadges() {
        removeAllFollowBadges()
        let labels = FollowBadgeLabels.labels(count: followCandidates.count)
        for (idx, candidate) in followCandidates.enumerated()
        where idx < labels.count {
            let viewBounds = convert(candidate.bounds, from: candidate.page)
            let badge = FollowBadgeView(letter: labels[idx])
            badge.frame = CGRect(x: viewBounds.midX - 9, y: viewBounds.midY - 9,
                                 width: 18, height: 18)
            addSubview(badge)
            followBadgeViews.append(badge)
        }
    }

    private func removeAllFollowBadges() {
        followBadgeViews.forEach { $0.removeFromSuperview() }
        followBadgeViews.removeAll()
    }

    /// 模式退出唯一出口：移除全部角标、还原轮换加深色、清候选、状态机
    /// 归零、收提示（不泄漏 subview）。
    private func exitFollowMode() {
        removeAllFollowBadges()
        if let annotation = followRotatedAnnotation {
            annotation.color = PDFDetailRepresentable.Coordinator.citationColor(hovered: false)
            followRotatedAnnotation = nil
        }
        followCandidates = []
        armedState.cancel()
        onReaderHint?(nil)
        needsDisplay = true
    }

    private func consumeFollowKey(_ event: NSEvent) -> Bool {
        let count = followCandidates.count
        switch event.keyCode {
        case 123: // ◀
            _ = armedState.retreatRotation(candidateCount: count)
            updateRotationVisual()
            onReaderHint?(followStatus())
            return true
        case 124, 49: // ▶ / 空格轮换（Sioyek preview N/M 对应物）
            _ = armedState.advanceRotation(candidateCount: count)
            updateRotationVisual()
            onReaderHint?(followStatus())
            return true
        case 36, 76, 108: // 回车（主/小键盘）选定当前轮换项
            selectFollowCandidate(at: armedState.rotationIndex)
            return true
        default:
            break
        }
        if let char = event.charactersIgnoringModifiers?.first,
           char.isASCII, char.isLetter {
            let labels = FollowBadgeLabels.labels(count: count)
            if let idx = labels.firstIndex(of: char.lowercased()) {
                selectFollowCandidate(at: idx)
                return true
            }
        }
        // 其他键：退出模式并放行原事件。
        exitFollowMode()
        return false
    }

    private func followStatus() -> String {
        L10n.followBanner(total: followCandidates.count,
                          current: armedState.rotationIndex + 1)
    }

    /// 选定候选：统一走 dispatchCitationTarget（mouseDown 同一分支），
    /// 完成即退模式。
    private func selectFollowCandidate(at index: Int) {
        defer { exitFollowMode() }
        guard followCandidates.indices.contains(index) else { return }
        dispatchCitationTarget(followCandidates[index].match)
    }

    /// 轮换视觉：当前项引文下划线加深（citationColor(hovered:) 既有色对），
    /// 旧项还原。
    private func updateRotationVisual() {
        if let annotation = followRotatedAnnotation {
            annotation.color = PDFDetailRepresentable.Coordinator.citationColor(hovered: false)
            followRotatedAnnotation = nil
        }
        guard case .armed(.follow) = armedState.phase,
              followCandidates.indices.contains(armedState.rotationIndex) else { return }
        let candidate = followCandidates[armedState.rotationIndex]
        let isCitation: (PDFAnnotation) -> Bool = { annotation in
            annotation.type == PDFAnnotationSubtype.underline.rawValue &&
            annotation.bounds == candidate.bounds &&
            (annotation.value(forAnnotationKey: AnnotationKindMarker.key) as? String) == AnnotationKindMarker.citation
        }
        if let annotation = candidate.page.annotations.first(where: isCitation) {
            annotation.color = PDFDetailRepresentable.Coordinator.citationColor(hovered: true)
            followRotatedAnnotation = annotation
        }
        needsDisplay = true
    }

    /// 命中的若是带 user 标记者内存标注，弹出操作菜单并返回 true；
    /// 标注上携带的 highlightID/color 键驱动换色/切样式/删除（落库后经
    /// onUserHighlightAdded 版本号重贴）。未命中返回 false 走默认行为。
    private func presentUserHighlightMenuIfNeeded(at event: NSEvent) -> Bool {
        let point = convert(event.locationInWindow, from: nil)
        guard let page = page(for: point, nearest: false),
              let annotation = page.annotation(at: convert(point, to: page)),
              (annotation.value(forAnnotationKey: AnnotationKindMarker.key) as? String) == AnnotationKindMarker.user,
              let store = highlightStore,
              let id = (annotation.value(forAnnotationKey: AnnotationKindMarker.highlightIDKey) as? NSNumber)?.int64Value
        else { return false }
        let colorRaw = (annotation.value(forAnnotationKey: AnnotationKindMarker.colorKey) as? String)
            ?? HighlightColor.yellow.rawValue
        let currentColor = HighlightColor(rawValue: colorRaw) ?? .yellow
        let currentStyle = annotation.type == PDFAnnotationSubtype.underline.rawValue ? "underline" : "highlight"
        let target = UserHighlightMenuTarget(
            id: id, currentColor: currentColor, currentStyle: currentStyle, store: store,
            onChanged: { [weak self] in self?.onUserHighlightAdded?() },
            onDelete: { [weak self] in self?.onUserHighlightDeleted?($0) })
        let menu = NSMenu()
        let colors: [(String, HighlightColor, Selector)] = [
            (L10n.menuHighlightYellow, .yellow, #selector(UserHighlightMenuTarget.recolorYellow)),
            (L10n.menuHighlightGreen, .green, #selector(UserHighlightMenuTarget.recolorGreen)),
            (L10n.menuHighlightBlue, .blue, #selector(UserHighlightMenuTarget.recolorBlue)),
            (L10n.menuHighlightRed, .red, #selector(UserHighlightMenuTarget.recolorRed)),
        ]
        for (title, _, selector) in colors {
            let item = NSMenuItem(title: title, action: selector, keyEquivalent: "")
            item.target = target
            menu.addItem(item)
        }
        menu.addItem(.separator())
        let toggle = NSMenuItem(
            title: currentStyle == "underline" ? L10n.changeToHighlight : L10n.changeToUnderline,
            action: #selector(UserHighlightMenuTarget.toggleStyle), keyEquivalent: "")
        toggle.target = target
        menu.addItem(toggle)
        let deleteItem = NSMenuItem(title: L10n.actionDelete,
                                    action: #selector(UserHighlightMenuTarget.deleteHighlight), keyEquivalent: "")
        deleteItem.target = target
        menu.addItem(deleteItem)
        // NSMenuItem.target is weak — keep the target alive with the menu.
        objc_setAssociatedObject(menu, "user-highlight-target", target, .OBJC_ASSOCIATION_RETAIN)
        menu.popUp(positioning: nil, at: point, in: self)
        return true
    }

    /// 事件点 → 引文命中（match + 覆盖该区间的 citation 标注 + 页索引）。
    private func citationMatch(at event: NSEvent)
        -> (match: CitationMatch, annotation: PDFAnnotation, pageIndex: Int)? {
        citationMatch(atViewPoint: convert(event.locationInWindow, from: nil))
    }

    private func citationMatch(atViewPoint point: NSPoint)
        -> (match: CitationMatch, annotation: PDFAnnotation, pageIndex: Int)? {
        guard let document, let page = page(for: point, nearest: false) else { return nil }
        let pageIndex = document.index(for: page)
        let pagePoint = convert(point, to: page)
        guard let entries = citationRects[pageIndex] else { return nil }
        for (bounds, match) in entries {
            // 命中区纵向放宽 2pt：细虚线本身只有零点几磅高。
            guard bounds.insetBy(dx: 0, dy: -2).contains(pagePoint) else { continue }
            let annotation = page.annotations.first {
                $0.type == PDFAnnotationSubtype.underline.rawValue &&
                $0.bounds == bounds &&
                ($0.value(forAnnotationKey: AnnotationKindMarker.key) as? String) == AnnotationKindMarker.citation
            }
            if let annotation { return (match, annotation, pageIndex) }
        }
        return nil
    }

    private func restoreHoveredCitation() {
        hoveredCitation?.color = PDFDetailRepresentable.Coordinator.citationColor(hovered: false)
        hoveredCitation = nil
    }

    /// Selection → utf16 range on its FIRST page: `PDFSelection.range(at:on:)`
    /// (selection-pages index 0 + that page) is the primary API
    /// (NSNotFound = unavailable); fallback is an anchored `range(of:)` of the
    /// selected text in the page string, measured in NSString/utf16 offsets.
    /// Final guard lives at the call site: 0 <= start < end <= page utf16 count.
    static func selectionUTF16Range(_ selection: PDFSelection, page: PDFPage) -> Range<Int>? {
        let ns = selection.range(at: 0, on: page)
        if ns.location != NSNotFound, ns.length > 0 {
            return ns.location..<(ns.location + ns.length)
        }
        guard let selected = selection.string, let pageText = page.string else { return nil }
        let trimmed = selected.trimmingCharacters(in: .whitespacesAndNewlines)
        let needle = trimmed.isEmpty ? selected : trimmed
        let found = (pageText as NSString).range(of: needle)
        guard found.location != NSNotFound, found.length > 0 else { return nil }
        return found.location..<(found.location + found.length)
    }

    private func quoteMenuIfSelected() -> NSMenu? {
        guard let selection = currentSelection,
              let raw = selection.string?.trimmingCharacters(in: .whitespacesAndNewlines),
              !raw.isEmpty else { return nil }
        let ctx = citationContext()
        guard !ctx.fileName.isEmpty else { return nil }
        // Physical page of the FIRST page carrying the selection.
        let firstPage = selection.pages.first
        let page = firstPage.flatMap { document?.index(for: $0) }.map { $0 + 1 }
        let utf16Range = firstPage.flatMap { Self.selectionUTF16Range(selection, page: $0) }
            .flatMap { range -> Range<Int>? in
                guard let count = firstPage?.string?.utf16.count,
                      range.lowerBound >= 0, range.upperBound <= count,
                      range.lowerBound < range.upperBound else { return nil }
                return range
            }
        // 拿得到页面全文 + utf16 区间时，引文文本改走纯函数规整
        // （补全被切断的整词、合并换行）；拿不到就退回 raw（行为不变）。
        // 高亮/收藏仍用 utf16Range 原值，不用规整后的文本。
        let quote: String = {
            guard let text = firstPage?.string, let range = utf16Range,
                  let normalized = QuoteTextNormalizer.normalize(pageText: text, utf16Range: range),
                  !normalized.isEmpty else { return raw }
            return normalized
        }()
        let bookID = bookIDProvider()
        let printed = page.flatMap { printedPageProvider?($0) } ?? nil
        // 页码优先序 page_map 印刷页 → 声明的 /PageLabels 标签
        // （阿拉伯/罗马数字）→ 物理页。只采信文档结构声明过的标签
        // （PDFKit 对未声明文档会伪造 "1","2"…）；声明结果按文档缓存。
        let label: String? = {
            guard printed == nil, let docURL = documentURL, let pageObject = firstPage,
                  PageLabelDeclaration.cachedDeclaration(
                    documentKey: PageLabelDeclaration.documentKey(fileURL: docURL),
                    fileURL: docURL) else { return nil }
            return pageObject.label
        }()
        let target = QuoteMenuTarget(quote: quote, fileName: ctx.fileName, title: ctx.title, page: page,
                                     pageObject: firstPage, utf16Range: utf16Range,
                                     highlightStore: highlightStore, favoritesStore: favoritesStore,
                                     bookID: bookID, isOriginalView: isOriginalViewProvider(),
                                     onUserHighlightAdded: onUserHighlightAdded,
                                     onTranslate: onTranslateRequest,
                                     printedPage: printed, pageLabel: label)
        let menu = NSMenu()
        let items = [
            NSMenuItem(title: L10n.menuQuotationFaxue,
                       action: #selector(QuoteMenuTarget.copyQuotationFaxue), keyEquivalent: ""),
            NSMenuItem(title: L10n.menuQuotationZGF,
                       action: #selector(QuoteMenuTarget.copyQuotationZGF), keyEquivalent: ""),
            NSMenuItem(title: L10n.menuSourceCitation,
                       action: #selector(QuoteMenuTarget.copySourceCitation), keyEquivalent: ""),
            // （PDF 菜单部分）：纯引注项——只有出处、绝不含原文片段，
            // 与上方「复制直接引文（含原文）」两项在标签上明确区分。
            NSMenuItem(title: L10n.copyCitationFaxue,
                       action: #selector(QuoteMenuTarget.copyCitationFaxue), keyEquivalent: ""),
            NSMenuItem(title: L10n.copyCitationZGF,
                       action: #selector(QuoteMenuTarget.copyCitationZGF), keyEquivalent: ""),
            NSMenuItem(title: L10n.menuCopySelectedText,
                       action: #selector(QuoteMenuTarget.copySelectedText), keyEquivalent: ""),
        ]
        for item in items {
            item.target = target
            menu.addItem(item)
        }
        // 追加项：既有四项保持原序原样。「添加高亮」为四色子菜单；
        // 「添加到收藏」把当前页写入收藏（坐标 = 选区 utf16 区间，可空）。
        if target.canHighlight {
            let submenu = NSMenu()
            let colors: [(String, HighlightColor)] = [
                (L10n.menuHighlightYellow, .yellow), (L10n.menuHighlightGreen, .green),
                (L10n.menuHighlightBlue, .blue), (L10n.menuHighlightRed, .red),
            ]
            let selectors: [Selector] = [#selector(QuoteMenuTarget.addHighlightYellow),
                                         #selector(QuoteMenuTarget.addHighlightGreen),
                                         #selector(QuoteMenuTarget.addHighlightBlue),
                                         #selector(QuoteMenuTarget.addHighlightRed)]
            for (index, entry) in colors.enumerated() {
                let item = NSMenuItem(title: entry.0, action: selectors[index], keyEquivalent: "")
                item.target = target
                submenu.addItem(item)
            }
            let parent = NSMenuItem(title: L10n.menuAddHighlight, action: nil, keyEquivalent: "")
            parent.submenu = submenu
            menu.addItem(parent)
        }
        if target.canFavorite {
            let item = NSMenuItem(title: L10n.menuAddPageFavorite,
                                  action: #selector(QuoteMenuTarget.favoritePage), keyEquivalent: "")
            item.target = target
            menu.addItem(item)
        }
        // 划词翻译：预填 prompt 进既有 AI 确认门（预览→逐次确认，零请求
        // 保证不变）。AI 未配置时两项禁用并附提示行。
        menu.addItem(.separator())
        let aiOn = aiConfiguredProvider()
        let zhItem = NSMenuItem(title: L10n.quickTranslateZH,
                                action: #selector(QuoteMenuTarget.translateToZH), keyEquivalent: "")
        zhItem.target = target
        zhItem.isEnabled = aiOn
        menu.addItem(zhItem)
        let enItem = NSMenuItem(title: L10n.quickTranslateEN,
                                action: #selector(QuoteMenuTarget.translateToEN), keyEquivalent: "")
        enItem.target = target
        enItem.isEnabled = aiOn
        menu.addItem(enItem)
        if !aiOn {
            let hint = NSMenuItem(title: L10n.aiUnconfigured, action: nil, keyEquivalent: "")
            hint.isEnabled = false
            menu.addItem(hint)
        }
        // NSMenuItem.target is weak — keep the target alive with the menu.
        objc_setAssociatedObject(menu, "quote-target", target, .OBJC_ASSOCIATION_RETAIN)
        return menu
    }
}

