    /// 程序化 setCurrentSelection（命中跳转/文档检索回选）置位此标记，
    /// currentSelection KVO 回调据此不弹浮动操作条。runloop 末清除，覆盖
    /// 延迟投递的 KVO 通知。
    private(set) var isProgrammaticSelection = false

    override func setCurrentSelection(_ selection: PDFSelection?, animate: Bool) {
        isProgrammaticSelection = true
        super.setCurrentSelection(selection, animate: animate)
        DispatchQueue.main.async { [weak self] in self?.isProgrammaticSelection = false }
    }

    /// 统一的用户高亮标注构建——style "underline" → .underline 标注，
    /// 其余 → .highlight（颜色同色）；携带 kind/highlightID/color 键，支撑
    /// 点击既有高亮的操作菜单与按标记者清退。纯内存标注，原书文件只读。
    static func makeUserAnnotation(id: Int64, color: HighlightColor,
                                   style: String, bounds: CGRect) -> PDFAnnotation {
        let subtype: PDFAnnotationSubtype = style == "underline" ? .underline : .highlight
        let annotation = PDFAnnotation(bounds: bounds, forType: subtype, withProperties: nil)
        annotation.color = NSColor(litHex: color.colorHex)
        annotation.setValue(AnnotationKindMarker.user, forAnnotationKey: AnnotationKindMarker.key)
        annotation.setValue(NSNumber(value: id), forAnnotationKey: AnnotationKindMarker.highlightIDKey)
        annotation.setValue(color.rawValue, forAnnotationKey: AnnotationKindMarker.colorKey)
        return annotation
    }

    /// PDFView doesn't reliably route right-clicks through menu(for:), so the
