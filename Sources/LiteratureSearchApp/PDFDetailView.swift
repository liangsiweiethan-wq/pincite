    /// 选区菜单「添加高亮」成功后回调（代表层据此 +1 版本号触发重贴）。
    let onUserHighlightAdded: (() -> Void)?
    /// 划词翻译请求（文本, 是否译成英文）；nil = 菜单项禁用。
    let onTranslate: ((String, Bool) -> Void)?

    init(quote: String, fileName: String, title: String?, page: Int?,
         pageObject: PDFPage? = nil, utf16Range: Range<Int>? = nil,
         highlightStore: HighlightStore? = nil, favoritesStore: FavoritesStore? = nil,
         bookID: String? = nil, isOriginalView: Bool = false,
         onUserHighlightAdded: (() -> Void)? = nil,
         onTranslate: ((String, Bool) -> Void)? = nil,
         printedPage: Int? = nil, pageLabel: String? = nil) {
        self.quote = quote
        self.fileName = fileName
        self.title = title
        self.page = page
        self.pageObject = pageObject
        self.utf16Range = utf16Range
        self.highlightStore = highlightStore
        self.favoritesStore = favoritesStore
        self.bookID = bookID
        self.printedPage = printedPage
        self.pageLabel = pageLabel
        self.isOriginalView = isOriginalView
        self.onUserHighlightAdded = onUserHighlightAdded
        self.onTranslate = onTranslate
    }

    var canHighlight: Bool {
        highlightStore != nil && bookID != nil && page != nil && pageObject != nil && utf16Range != nil
    }

    var canFavorite: Bool {
        favoritesStore != nil && bookID != nil && page != nil
    }

    private func paste(_ text: String) {
        NSPasteboard.general.clearContents()
        NSPasteboard.general.setString(text, forType: .string)
    }

    @objc func copyQuotationFaxue() {
        paste(CitationFormatter.quotation(quote: quote, fileName: fileName, title: title,
                                          physicalPage: page, style: .faxueYinzhuShouce,
                                          printedPage: printedPage, pageLabel: pageLabel))
    }

    @objc func copyQuotationZGF() {
        paste(CitationFormatter.quotation(quote: quote, fileName: fileName, title: title,
                                          physicalPage: page, style: .zhongguoFaxue,
                                          printedPage: printedPage, pageLabel: pageLabel))
    }

    @objc func copySourceCitation() {
        paste(CitationFormatter.citation(fileName: fileName, title: title,
                                         physicalPage: page, style: .faxueYinzhuShouce,
                                         printedPage: printedPage, pageLabel: pageLabel))
    }

    /// （PDF 菜单部分）：纯引注（无原文片段），两种体例各一项。
    @objc func copyCitationFaxue() {
        paste(CitationFormatter.citation(fileName: fileName, title: title,
                                         physicalPage: page, style: .faxueYinzhuShouce,
                                         printedPage: printedPage, pageLabel: pageLabel))
    }

    @objc func copyCitationZGF() {
        paste(CitationFormatter.citation(fileName: fileName, title: title,
                                         physicalPage: page, style: .zhongguoFaxue,
                                         printedPage: printedPage, pageLabel: pageLabel))
    }

    @objc func copySelectedText() {
        paste(quote)
    }

    // MARK: 高亮 / 收藏（内存标注 + 索引库写入；原件永远只读）

    @objc func addHighlightYellow() { addHighlight(.yellow) }
    @objc func addHighlightGreen() { addHighlight(.green) }
    @objc func addHighlightBlue() { addHighlight(.blue) }
    @objc func addHighlightRed() { addHighlight(.red) }

    /// 写入 HighlightStore 并立即在内存页面上叠加同区间高亮标注
    /// （user 标记——检索命中清退不会带走它；颜色取 HighlightColor.colorHex；
    /// 记录选中文本作为抗漂移锚点）。：写入带当前视图来源
    /// （默认 'ocr' / 原件 'original'），页码即产生选区的文件的物理页。
    private func addHighlight(_ color: HighlightColor) {
        guard let highlightStore, let bookID, let utf16Range, let pageObject, let page else { return }
        guard utf16Range.upperBound <= (pageObject.string?.utf16.count ?? 0) else { return }
        let anchor = String(quote.prefix(200))
        let viewSource = isOriginalView ? HighlightStore.viewSourceOriginal
                                        : HighlightStore.viewSourceOCR
        guard let newID = try? highlightStore.add(bookID: bookID, pageNumber: page,
                                                  utf16Start: utf16Range.lowerBound, utf16End: utf16Range.upperBound,
                                                  color: color, note: "", anchorText: anchor,
                                                  viewSource: viewSource)
        else { return }
        let ns = NSRange(location: utf16Range.lowerBound, length: utf16Range.upperBound - utf16Range.lowerBound)
        guard let selection = pageObject.selection(for: ns),
              let bounds = selection.bounds(for: pageObject) as CGRect? else { return }
        let annotation = QuotePDFView.makeUserAnnotation(id: newID, color: color,
                                                         style: "highlight", bounds: bounds)
        pageObject.addAnnotation(annotation)
        onUserHighlightAdded?()
    }

    @objc func favoritePage() {
        guard let favoritesStore, let bookID, let page else { return }
        _ = try? favoritesStore.add(.page(bookID: bookID, fileName: fileName, pageNumber: page,
                                          snippet: quote,
                                          utf16Start: utf16Range?.lowerBound,
                                          utf16End: utf16Range?.upperBound))
    }

    // MARK: 划词翻译（闭包由详情栏注入：预填 prompt → 既有 AI 确认门）

    @objc func translateToZH() { onTranslate?(quote, false) }
    @objc func translateToEN() { onTranslate?(quote, true) }
}

/// 点击既有用户高亮弹出的操作菜单目标（换色/切样式/删除）。
/// 全部走 HighlightStore 写接口 + onChanged 版本号重贴；内存标注、原件只读。
final class UserHighlightMenuTarget: NSObject {
    let id: Int64
    let currentColor: HighlightColor
    let currentStyle: String
    let store: HighlightStore
    let onChanged: () -> Void
    /// 删除上抛（AppState 软删 + toast 撤销通道；nil = 回退本地
    /// 软删——语义同为墓碑，只是无全局 toast）。
    let onDelete: ((Int64) -> Void)?

    init(id: Int64, currentColor: HighlightColor, currentStyle: String,
         store: HighlightStore, onChanged: @escaping () -> Void,
         onDelete: ((Int64) -> Void)? = nil) {
        self.id = id
        self.currentColor = currentColor
        self.currentStyle = currentStyle
        self.store = store
        self.onChanged = onChanged
        self.onDelete = onDelete
    }

    @objc func recolorYellow() { recolor(.yellow) }
    @objc func recolorGreen() { recolor(.green) }
    @objc func recolorBlue() { recolor(.blue) }
    @objc func recolorRed() { recolor(.red) }

    private func recolor(_ color: HighlightColor) {
        try? store.updateAppearance(id: id, color: color, style: currentStyle)
        onChanged()
    }

    @objc func toggleStyle() {
        let next = currentStyle == "underline" ? "highlight" : "underline"
        try? store.updateAppearance(id: id, color: currentColor, style: next)
        onChanged()
    }

    @objc func deleteHighlight() {
        // 软删（deleted_at 墓碑），硬删 API 保留不再由 UI 调用。
        if let onDelete {
            onDelete(id)
        } else {
            try? store.softDelete(id: id)
            onChanged()
        }
    }
}

// MARK: - 缩略图栏（PDFKit 现成 PDFThumbnailView）
//
// 与 PDFView 同 document 实例联动：thumbnailView.pdfView 赋值即共享文档、
// 点击跳页、随当前页同步高亮；pdfView 为 nil（加载中/指纹失效）时缩略图
// 自然为空。纯 PDFKit 本地组件，零网络。

struct PDFThumbnailRepresentable: NSViewRepresentable {
    /// 阅读器桥（详情栏持有，与 PDFDetailView 同一实例）。
    let readerState: PDFReaderState

    func makeNSView(context: Context) -> PDFThumbnailView {
        let view = PDFThumbnailView()
        // PDFThumbnailView 无 layoutMode API（横向排布属 PDFView.displayMode
        // 体系）；120 宽栏内缩略图自动顺排，栏宽即版式约束。
        view.thumbnailSize = CGSize(width: 120, height: 120)
        view.pdfView = readerState.pdfView
        return view
    }

    func updateNSView(_ view: PDFThumbnailView, context: Context) {
        if view.pdfView !== readerState.pdfView {
            view.pdfView = readerState.pdfView
        }
    }
}

// MARK: - f 键候选字母角标（小圆底＋字母；inkSecondary 系色，
// 不新增琥珀位点——约束：琥珀零新增位点）。纯展示 NSView，只在装载时
// 入层级、模式退出时移除（不泄漏 subview）。

private final class FollowBadgeView: NSView {
    private let letter: String

    init(letter: String) {
        self.letter = letter
        super.init(frame: .zero)
        wantsLayer = true
        layer?.cornerRadius = 9
        layer?.masksToBounds = true
        // 色取 Smart Jump 引文层 hover 深化色（Coordinator.citationColor
        // 既有色对；轻微提不透明度保字母可读）。
        layer?.backgroundColor = PDFDetailRepresentable.Coordinator
            .citationColor(hovered: true)
            .withAlphaComponent(0.92)
            .cgColor
    }

    @available(*, unavailable)
    required init?(coder: NSCoder) { nil }

    override func draw(_ dirtyRect: NSRect) {
        let paragraph = NSMutableParagraphStyle()
        paragraph.alignment = .center
        let attributes: [NSAttributedString.Key: Any] = [
            .font: NSFont.systemFont(ofSize: 10, weight: .semibold),
            .foregroundColor: NSColor.white,
            .paragraphStyle: paragraph,
        ]
        let size = (letter as NSString).size(withAttributes: attributes)
        (letter as NSString).draw(
            at: NSPoint(x: (bounds.width - size.width) / 2,
                        y: (bounds.height - size.height) / 2),
            withAttributes: attributes)
    }
}
