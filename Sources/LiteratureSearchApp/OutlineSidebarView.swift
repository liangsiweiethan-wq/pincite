import SwiftUI
import AppKit
import LiteratureSearchUI

/// 目录节点（值类型，从 PDFOutline 递归展平；page 为 1 起物理页，nil =
/// 目的地缺失/外部文件，行禁用）的展示扩展：List(children:) 要求可选
/// keypath（nil = 叶子节点），空数组统一降级为 nil。
extension PDFOutlineNode {
    var childNodes: [PDFOutlineNode]? { children.isEmpty ? nil : children }
}

// MARK: - 目录侧栏（PDFOutline 树）
//
// 树数据源是阅读器桥 readerState.outline（Coordinator 在 finishLoad 从
// PDFDocument.outlineRoot 递归展平；无目录书恒为空数组，工具栏按钮与
// 本栏都不渲染）。展示用 SwiftUI List(children: \.children)——递归子节点
// 展开/收起与行虚拟化（懒加载）由 List 自带 OutlineGroup 承担，本文件零
// 自绘树逻辑。点击行 → readerState.jump(to:) → Coordinator 注入的
// 跳页回调（1 起物理页，fail-closed）；目的地缺失（page == nil）的行
// 禁用并灰显。

/// 目录侧栏：左缘内嵌，宽 220，可滚动；与缩略图栏并列、互不从属。
struct OutlineSidebarView: View {
    @ObservedObject var readerState: PDFReaderState
    @Environment(\.colorScheme) private var scheme
    @AppStorage("dsTheme") private var dsTheme = DS.Theme.system.rawValue

    var body: some View {
        let theme = DS.Theme.storage(dsTheme)
        VStack(spacing: 0) {
            List(readerState.outline, children: \.childNodes) { node in
                OutlineRow(node: node, theme: theme, scheme: scheme) {
                    if let page = node.page {
                        readerState.jump(to: page)
                    }
                }
            }
            .listStyle(.sidebar)
            .scrollContentBackground(.hidden)
            // 自动目录回退时底部标注来源；原生书签书不显示此行。
            if readerState.outlineAutoGenerated {
                Text(L10n.outlineAutoGenerated)
                    .font(.caption2)
                    .foregroundStyle(DS.Color.inkTertiary(theme, scheme))
                    .frame(maxWidth: .infinity)
                    .padding(.vertical, DS.Spacing.xs)
                    .background(DS.Color.desk(theme, scheme))
            }
        }
        .background(DS.Color.desk(theme, scheme))
        .accessibilityLabel(L10n.outlineToggle)
    }
}

/// 单行：目录 label（缩进由 List 层级自带）；page 为 nil（目的地缺失/
/// 外部文件）整行禁用并灰显，可跳行 hover 主色提示。
private struct OutlineRow: View {    let node: PDFOutlineNode
    let theme: DS.Theme
    let scheme: ColorScheme
    let onJump: () -> Void

    var body: some View {
        Button(action: onJump) {
            HStack(spacing: DS.Spacing.xs) {
                Text(node.label)
                    .font(.callout)
                    // 自动目录条目的层级缩进（原生书签恒 0，由 List 层级自带）。
                    .padding(.leading, CGFloat(node.indent) * 12)
                    .lineLimit(1)
                    .foregroundStyle(node.page == nil
                                     ? DS.Color.inkTertiary(theme, scheme)
                                     : DS.Color.ink(theme, scheme))
                Spacer(minLength: 0)
            }
            .contentShape(Rectangle())
        }
        .buttonStyle(.plain)
        .disabled(node.page == nil)
    }
}
